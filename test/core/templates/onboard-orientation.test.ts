import { describe, it, expect } from 'vitest';
import { getOnboardSkillTemplate } from '../../../src/core/templates/workflows/onboard.js';

/**
 * landing-page task 2.2 (design D6) — the onboard body's Section 1, `orbit-onboard`'s `Orientation
 * section`: orbit's own version (`orbit --version`, 2.0.0 from this stage on) is stated apart from the
 * upstream engine baseline 1.3.1, never as one number.
 */

const onboard = getOnboardSkillTemplate().instructions;
const start = onboard.indexOf('## Section 1: Orientation');
const end = onboard.indexOf('## Section 2:', start);
const section = onboard.slice(start, end);

describe('landing-page — the onboard Orientation section', () => {
  it('is found, and ends before Section 2', () => {
    expect(start).toBeGreaterThanOrEqual(0);
    expect(end).toBeGreaterThan(start);
  });

  // @scenario text orbit-onboard :: Orientation section :: States the self-contained model
  it('states the self-contained model: a hard fork of openspec@1.3.1 with nothing to overlay', () => {
    expect(section).toContain('**self-contained**');
    expect(section).toContain('a hard fork of openspec@1.3.1');
    expect(section).toContain('nothing to "overlay"');
  });

  // @scenario text orbit-onboard :: Orientation section :: Points at the CLI and workspace
  it('names `orbit --version` as printing orbit\'s own version, and the 1.3.1 baseline in a separate sentence', () => {
    const cli = section.split('\n').find((l) => l.startsWith('- **CLI**:'))!;
    expect(cli).toBeDefined();
    const sentences = cli.split(/(?<=\.)\s+/);
    const version = sentences.find((s) => s.includes('`orbit --version`'))!;
    expect(version).toContain("it prints orbit's own version");
    expect(version).not.toContain('1.3.1');
    expect(sentences.find((s) => s.includes('1.3.1'))).toContain('the engine is pinned at the upstream baseline 1.3.1');
    expect(section).not.toContain('the pinned engine version is 1.3.1');
    expect(section).toContain('`orbit/` holds your specs (`orbit/specs/`) and in-flight changes (`orbit/changes/`)');
    expect(section).toContain('run `orbit init` first');
    expect(section).toContain('generated by `orbit init`');
  });

  // @scenario text orbit-onboard :: Orientation section :: No gating, no overlay-integrity checks
  it('carries no gate, no surface count, no feedback-skill check and no overlay verification', () => {
    expect(section).toContain('No install verification needed.');
    for (const p of ['STOP', 'hard-stop', 'feedback', 'count the', 'skills installed', 'verify the overlay']) {
      expect(section).not.toContain(p);
    }
  });
});
